# Special Characters

# Escape Sequences
print("Hello, World!")  # Regular string
print("Hello, \nWorld!")  # New line character
print("Hello, \tWorld!")  # Tab character
print("Hello, \"World\"!")  # Double quote character
print("Hello, 'World'!")  # Single quote character
print('path: C:\\Users\\Name\\Documents')  # Backslash character
print("Hello, \bWorld!")  # Backspace character

# Example of using special characters in a learning path
print('Your Learning Path:\n \t-Python Programming\n \t-Data Engineering\n \t-AI')




## Variables

